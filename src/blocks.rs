//! Блочная модель: канонический предикат «это шаг». Всё остальное — блоки
//! (text/image/poll/…), несущие type/content. Пустая строка приравнена к 'step':
//! proto3 не отличает '' от отсутствия поля, БД хранит 'step' явно.
/// Шаг ли это (все прочие типы — блоки с type/content).
pub fn is_step_type(t: &str) -> bool {
    t.is_empty() || t == "step"
}
