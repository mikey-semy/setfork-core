//! Кто считается автором пуша.
//!
//! Правило жило внутри `receive_pack` семь недель и не было закрыто ничем: мутация
//! проходила незамеченной, потому что тесты гоняют ХУК, а выбор происходит до хука
//! (линза 10, 10-F11). Вынесено ради проверяемости, а не ради красоты.

/// Кто считается автором пуша: идентификатор, ник или никто.
///
/// ПЕРЕХОДНОЕ (снять вместе с полем `actor_handle`): фронт старше Ф5 шлёт только ник.
/// Без запасного пути такое ядро отвергало бы КАЖДЫЙ магический пуш до выката фронта —
/// то есть при обратном порядке выкатки функция ложится ровно так же, как ложилась бы у
/// старого ядра без переходного поля (авто-ревью fe#662).
///
/// Признак «фронт старше» — ПУСТАЯ РОЛЬ, а не пустой идентификатор. Иначе запасной путь
/// ловил бы и запрос от нового фронта, где `actor_id` забыт по ошибке: ветка называлась бы
/// по СМЕНЯЕМОМУ нику, и после смены ника чужой человек перезаписал бы предъявленное
/// (авто-ревью core#80, P1). Новый фронт без идентификатора — это неисправность, и
/// магический реф обязан отвергнуться, как обещает протокол.
///
/// ⚠️ Вынесено из тела `receive_pack` не ради красоты: правило жило там семь недель и не
/// было закрыто ничем. Мутация 25.08 (склеить обе пустые ветки в одну) прошла НЕЗАМЕЧЕННОЙ
/// — восемь тестов `contributor_namespace` остались зелёными, потому что гоняют хук, а
/// этот выбор происходит до хука (линза 10, находка 10-F11).
pub(super) fn choose_actor(actor_id: &str, actor_role: &str, actor_handle: &str) -> String {
    match (actor_id, actor_role) {
        ("", "") => actor_handle.to_string(),
        ("", _) => String::new(),
        (id, _) => id.to_string(),
    }
}

// Формат принадлежит ядру: канон, собранный из структуры провода, обязан быть
// БАЙТ-В-БАЙТ тем же, что материализация версии кладёт в дерево коммита. Если
// эти два пути разойдутся, «правка в ветке» начнёт писать другой формат, чем push.
/// Регрессия 10-F11: правило выбора автора пуша жило внутри `receive_pack` и не было
/// закрыто ничем. Здесь оно закрыто ТРЕМЯ случаями — по одному на каждую ветку, потому
/// что цена у них разная: ошибка в первой ломает выкатку, во второй — отдаёт чужому
/// человеку предъявленную правку после смены ника.
#[cfg(test)]
mod actor_choice_tests {
    use super::choose_actor;

    #[test]
    fn old_frontend_is_recognized_by_an_empty_role() {
        assert_eq!(
            choose_actor("", "", "mike"),
            "mike",
            "фронт старше Ф5 шлёт только ник — иначе КАЖДЫЙ магический пуш отвергался бы до выката"
        );
    }

    #[test]
    fn new_frontend_without_id_does_not_fall_back_to_handle() {
        for role in ["owner", "contributor", "outsider", "невиданная"] {
            assert_eq!(
                choose_actor("", role, "mike"),
                "",
                "роль {role:?} прислана, а идентификатор забыт — это неисправность фронта, \
                 и магический реф обязан отвергнуться. Подставить ник нельзя: ник СМЕНЯЕМ, \
                 и после смены чужой человек перезаписал бы предъявленное (core#80)"
            );
        }
    }

    #[test]
    fn the_id_always_wins_over_the_handle() {
        let id = "11111111-2222-3333-4444-555555555555";
        for role in ["", "owner", "contributor"] {
            assert_eq!(choose_actor(id, role, "mike"), id, "при любой роли берётся идентификатор");
        }
    }
}
